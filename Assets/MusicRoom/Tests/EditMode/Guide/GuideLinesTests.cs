        [Test]
        public void ChirpTableIsTheOneTheEngineUses()
        {
            // guide-lines.json chirps: the engine's GuideVoice.Chirp stages these two tones per kind.
            ChirpsJ c = Load().chirps;
            Assert.That(c.open.Length, Is.EqualTo(2));
            Assert.That(c.close.Length, Is.EqualTo(2));
            Assert.That(new[] { c.open[0].at, c.open[0].f0, c.open[0].f1, c.open[0].slide, c.open[0].peak, c.open[0].decay, c.open[0].lp },
                Is.EqualTo(new[] { 0.01f, 880f, 1320f, 0.04f, 0.022f, 0.06f, 5000f }));
            Assert.That(new[] { c.open[1].at, c.open[1].f0, c.open[1].f1, c.open[1].slide, c.open[1].peak, c.open[1].decay },
                Is.EqualTo(new[] { 0.075f, 1320f, 700f, 0.05f, 0.018f, 0.07f }));
            Assert.That(new[] { c.close[0].at, c.close[0].f0, c.close[0].f1, c.close[0].peak, c.close[0].decay },
                Is.EqualTo(new[] { 0.02f, 1100f, 560f, 0.018f, 0.06f }));
            Assert.That(new[] { c.close[1].at, c.close[1].f0, c.close[1].f1, c.close[1].peak, c.close[1].decay },
                Is.EqualTo(new[] { 0.085f, 700f, 420f, 0.015f, 0.07f }));
            Assert.That(c.open[0].type, Is.EqualTo("square"));
        }

        [Test]
        public void VoiceClipsAreMono22kAndAsLongAsTheManifestSays()
        {
            for (int i = 0; i < GuideLines.Count; i++)
            {
                var clip = Resources.Load<AudioClip>("Voice/" + GuideLines.Ids[i]);
                Assert.That(clip, Is.Not.Null, GuideLines.Ids[i]);
                Assert.That(clip.channels, Is.EqualTo(1), "mono");
                Assert.That(clip.frequency, Is.EqualTo(22050));
                Assert.That(clip.length, Is.EqualTo(GuideLines.ManifestSeconds[i]).Within(0.001f), GuideLines.Ids[i]);
            }
            var manifest = Resources.Load<TextAsset>("Voice/manifest");
            Assert.That(manifest, Is.Not.Null);
            foreach (string id in GuideLines.Ids) Assert.That(manifest.text, Does.Contain("\"" + id + "\""));
        }
