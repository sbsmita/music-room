// Drift checks: Sunny's script and constants against Resources/guide-lines.json (the exported script, timing table
// and voice manifest), the voice WAVs against the manifest, and the
// module's line order against the audio engine's voice slots.
using System;
using MusicRoom.Audio.Synths;
using MusicRoom.Guide;
using System.Linq;
using NUnit.Framework;
using UnityEngine;

namespace MusicRoom.Tests.Guide
{
    public class GuideLinesTests
    {
#pragma warning disable 0649   // JsonUtility fills these
        [Serializable] class LineJ { public string id, text, spoken, file; public float seconds, lineSeconds; }
        [Serializable] class StepJ { public string id, demo, vr, desk, skip; }
        [Serializable] class OffsetJ { public float ahead, left, down; }
        [Serializable] class BobJ { public float amp, rateHz; }
        [Serializable] class MouthJ { public float open, close, floor, decayPerSecond; }
        [Serializable]
        class TimingJ
        {
            public float RADIUS, FOLLOW, STEP_TIMEOUT, INTRO_T, PRAISE_T, SKIP_T, BYE_T, LEAVE_T, LEAVE_RISE, PAD_FAR, BLINK_T, GAP, LATE, holdPadSeconds;
            public OffsetJ offset; public BobJ bob; public MouthJ mouth;
        }
        [Serializable] class RobotJ { public float rate, lead; }
        [Serializable] class ChirpJ { public float at, f0, f1, slide, peak, decay, lp; public string type; }
        [Serializable] class ChirpsJ { public ChirpJ[] open, close; }
        [Serializable] class FileJ { public int lineCount; public LineJ[] lines; public string[] praise; public StepJ[] steps; public TimingJ timing; public RobotJ robot; public ChirpsJ chirps; }
#pragma warning restore 0649

        /// <summary>The 22 original tour lines come first; the later lines follow.</summary>
        const int TourLines = 22;

        static FileJ Load()
        {
            var text = Resources.Load<TextAsset>("guide-lines");
            Assert.That(text, Is.Not.Null, "Guide/Resources/guide-lines.json");
            return JsonUtility.FromJson<FileJ>(text.text);
        }

        [Test]
        public void TheLinesMatchTheExportedTable()
        {
            FileJ f = Load();
            Assert.That(f.lineCount, Is.EqualTo(GuideLines.Count), "the 22 tour lines and the later ones (tip_arrange, tip_loop_start, the deck walkthrough)");
            Assert.That(f.lines.Length, Is.EqualTo(GuideLines.Count));
            Assert.That(GuideLines.Count, Is.EqualTo(38));
            // First five: the first run's and the tour's tips' lines are a module line file merged after the 38
            // (Resources/GuideLines/FirstFive.json, VoiceManifests/FirstFive.json; generated by Guide/Tools~/render-voice.mjs).
            // The quick tour (2026-11-04): 16 lines of the old first run retired, 7 tour lines added; the hands / drag work's
            // 4 (tip_handle_still, tip_handle_turn, tip_handle_play_first, tip_move_by_knob) and tip_bowl_sing reserved.
            // Move instruments as one setting (2026-11-10): the knob, Lock and height lines retired (tip_lock, tip_locked,
            // tip_arrange_lift, tip_handle, tip_handle_still, tip_handle_drop, tip_handle_turn, tip_handle_play_first,
            // tip_move_by_knob: 9), tip_move_turn_on and tip_move_quiet added; the playback work's tip_listen_back added.
            // The classic sound as the only sound (2026-11-10): tip_classic retired. Heights (2026-11-11): tip_move_height added.
            // The room comes alive while you record (2026-11-11): tip_record_glow added.
            // A recording brings its instruments (2026-11-11): tip_play_brings added.
            // The snowy window joins in with a playback (2026-11-11): tip_window_show added.
            // The song's night sky (2026-11-11): tip_song_stars added.
            // The notes paint the walls (2026-11-11): tip_paint_walls and tip_paint_keep added.
            // Ghost hands play it back (2026-11-11): tip_ghost_hands added.
            // The mixed reality snowy window removed (2026-11-13): tip_mr_snow, tip_mr_window, tip_mr_window_move retired.
            // Throwing paint and the gallery (2026-11-13): tip_paint_throw and tip_paint_gallery added.
            // Snow in the whole room (2026-11-13): tip_room_snow added.
            // Look and pinch (2026-11-13): tip_look_pinch added.
            // The deck's quick show (2026-11-14): quick_snow, quick_play and quick_wow added.
            // A fireplace in your room (2026-11-14): tip_mr_fire added.
            // Little friends dance to a playback (2026-11-14): tip_dance_buddies added.
            // The fast first-timer tour (2026-11-16): fast_snow, fast_move, fast_set, fast_rec, fast_saved, fast_recenter, fast_bye added.
            // The tune buddies removed (2026-11-17): tip_dance_buddies retired.
            // Record on top (2026-11-17): tip_record_on_top added.
            Assert.That(FirstFiveLines.Ids.Length, Is.EqualTo(93));
            Assert.That(FirstFiveLines.Ids[0], Is.EqualTo("start_help"), "the first run's lines first");
            foreach (string id in FirstFiveLines.Ids)
            {
                Assert.That(GuideLines.IndexOf(id), Is.EqualTo(-1), id + " is not one of the 38");
                Assert.IsTrue(GuideLines.Merged.Has(id), id + " is in GuideLines/FirstFive.json");
                Assert.That(GuideLines.SecondsOf(id), Is.GreaterThan(0f), id + " is in VoiceManifests/FirstFive.json");
                string text = GuideLines.TextOf(id), spoken = GuideLines.Merged.SpokenOf(id);
                Assert.That(spoken.ToLowerInvariant(), Is.EqualTo(text.ToLowerInvariant().Replace("hi-hat", "hi hat")), id + ": only an all-caps button name is spoken in lower case (and hi-hat as two words)");
            }
            // tip_arrange stays the 23rd line (u-arrange), the looper's 15 follow it.
            Assert.That(GuideLines.Ids[22], Is.EqualTo(GuideLines.TipArrange));
            Assert.That(GuideLines.TextOf(GuideLines.TipArrange), Is.EqualTo("Pinch an instrument and drag it where you like."));
            Assert.That(GuideLines.Ids[23], Is.EqualTo(GuideLines.TipLoopStart));
            Assert.That(GuideLines.Ids.Length, Is.EqualTo(GuideLines.Count));
            Assert.That(GuideLines.Texts.Length, Is.EqualTo(GuideLines.Count));
            Assert.That(GuideLines.ManifestSeconds.Length, Is.EqualTo(GuideLines.Count));
            for (int i = 0; i < f.lines.Length; i++)
            {
                LineJ l = f.lines[i];
                Assert.That(GuideLines.Ids[i], Is.EqualTo(l.id), "order of guide-lines.json");
                Assert.That(GuideLines.Texts[i], Is.EqualTo(l.text), l.id);
                if (i < TourLines) Assert.That(l.spoken, Is.EqualTo(l.text), "SPOKEN is empty: the recording says the caption");
                else Assert.That(l.spoken.ToLowerInvariant(), Is.EqualTo(l.text.ToLowerInvariant()), "Unity lines: only an all-caps button name is spoken in lower case");
                Assert.That(GuideLines.ManifestSeconds[i], Is.EqualTo(l.seconds).Within(1e-6f), l.id);
                Assert.That(GuideLines.TextOf(l.id), Is.EqualTo(l.text));
                Assert.That(l.lineSeconds, Is.EqualTo(l.seconds / GuideTiming.Rate + GuideTiming.Lead).Within(1e-4f), "lineSeconds = clip / rate + lead");
            }
            Assert.That(GuideLines.IndexOf("Any other words"), Is.EqualTo(-1));
            Assert.That(GuideLines.IndexOf(""), Is.EqualTo(-1));
            Assert.That(GuideLines.IndexOf(null), Is.EqualTo(-1));
        }

        [Test]
        public void LineOrderIsTheEnginesVoiceSlotOrder()
        {
            // The Guide's own table leads the engine's voice slots (EngineVoice maps ids to AudioEngine.VoiceSlot0 + index); the
            // lines merged from the modules' VoiceManifests follow it (platform.md 8.2).
            Assert.That(GuideVoice.LineIds.Take(GuideLines.Ids.Length), Is.EqualTo(GuideLines.Ids), "EngineVoice maps ids to AudioEngine.VoiceSlot0 + index");
            Assert.That(GuideVoice.Lead, Is.EqualTo(GuideTiming.Lead));
        }

        [Test]
        public void StepsPraiseAndSkipsMatchTheExport()
        {
            FileJ f = Load();
            Assert.That(GuideLines.Praise, Is.EqualTo(f.praise));
            Assert.That(GuideLines.Steps.Length, Is.EqualTo(f.steps.Length));
            string[] demos = { "", "palm", "poke", "swipe", "nod" };
            for (int i = 0; i < f.steps.Length; i++)
            {
                StepDef s = GuideLines.Steps[i];
                Assert.That(s.Id.ToString().ToLowerInvariant(), Is.EqualTo(f.steps[i].id));
                Assert.That(demos[(int)s.Demo], Is.EqualTo(f.steps[i].demo));
                Assert.That(s.Vr, Is.EqualTo(f.steps[i].vr));
                Assert.That(s.Desk, Is.EqualTo(f.steps[i].desk));
                bool timed = !string.IsNullOrEmpty(f.steps[i].skip);
                Assert.That(s.Skip ?? "", Is.EqualTo(f.steps[i].skip ?? ""));
                Assert.That(s.Timeout, Is.EqualTo(timed ? f.timing.STEP_TIMEOUT : 0f), "only the swipe and the nod time out");
                Assert.That(GuideLines.IsLine(s.Vr) && GuideLines.IsLine(s.Desk), Is.True);
            }
        }

