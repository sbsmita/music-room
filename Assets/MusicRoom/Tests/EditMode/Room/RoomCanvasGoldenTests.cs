// The 2D-drawn room textures (rug, brick, leaves, scenery, night sky) against the golden bytes: every table below
// was read from the reference textures drawn headless by Skia's CPU 2D rasteriser (a reference harness generated these
// tables). ARCHITECTURE.md section 15.4 (room textures against the reference formulas). Points are interior pixels of
// the golden image (its 5 x 5 neighbourhood
// within 3 levels, so no anti-aliased edge), plus named ones: the rug's field, both border strokes and diamond centres;
// each brick row's face and the mortar line above it (both row parities); the night sky's moon disc and its larger
// stars' centres. Tolerances, measured over every interior pixel: the flat fills (rug, brick) are exact; the gradient
// fills differ from Skia's fixed-point gradient evaluation by at most 2 levels (leaf, night sky; scenery 1). Edge
// pixels (Skia's anti-aliasing vs this code's coverage) are not compared, but the night sky's ridge lines are: per
// column, the first row of each hill's flat colour within one row.
