        [Test]
        public void NightSkyIsTheGoldenPixelsAndRidges()
        {
            var sky = RoomTexGen.NightSky();
            Check(sky, NightSky, 2, "night sky");
            int w = sky.Width, h = sky.Height;
            foreach (var r in NightRidges)
            {
                int x = r[0], far = -1, near = -1;
                for (int y = (int)(h * 0.6f); y < h; y++)
                {
                    Color32 c = sky.Pixels[(h - 1 - y) * w + x];
                    if (far < 0 && c.r == 13 && c.g == 18 && c.b == 38) far = y;
                    if (near < 0 && c.r == 7 && c.g == 10 && c.b == 22) { near = y; break; }
                }
                Assert.That(far, Is.EqualTo(r[1]).Within(1), $"far ridge at x {x}");
                Assert.That(near, Is.EqualTo(r[2]).Within(1), $"near ridge at x {x}");
            }
        }

