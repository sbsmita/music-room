        static void Check(PixelImage img, int[][] golden, int tolerance, string what)
        {
            foreach (var g in golden)
            {
                int x = g[0], y = g[1];
                Color32 c = img.Pixels[(img.Height - 1 - y) * img.Width + x];   // canvas row y -> texture row h-1-y
                int d = Mathf.Max(Mathf.Max(Mathf.Abs(c.r - g[2]), Mathf.Abs(c.g - g[3])), Mathf.Max(Mathf.Abs(c.b - g[4]), Mathf.Abs(c.a - g[5])));
                Assert.That(d, Is.LessThanOrEqualTo(tolerance), $"{what} ({x}, {y}): golden {g[2]},{g[3]},{g[4]},{g[5]} got {c.r},{c.g},{c.b},{c.a}");
            }
        }

        [Test] public void RugIsTheGoldenBytes() => Check(RoomTexGen.Rug(), Rug, 0, "rug");
        [Test] public void BrickIsTheGoldenBytes() => Check(RoomTexGen.Brick(), Brick, 0, "brick");

        [Test]
        public void LeavesAreTheGoldenPixels()
        {
            Check(RoomTexGen.Leaf(false, "leaf_light"), LeafLight, 2, "leaf light");
            Check(RoomTexGen.Leaf(true, "leaf_dark"), LeafDark, 2, "leaf dark");
