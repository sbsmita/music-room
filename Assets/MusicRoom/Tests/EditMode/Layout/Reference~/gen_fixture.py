# Converts layout-golden.json (the frozen layout golden: right-handed coordinates, -z forward) into the C# fixture
# used by the Unity Layout tests (Unity coordinates: z negated, yaw negated, local z negated).
# Usage: python3 -I gen_fixture.py layout-golden.json <out.cs> <namespace>
import json, math, sys

src, out_path, ns = sys.argv[1], sys.argv[2], sys.argv[3]
d = json.load(open(src))
RIGS = ['piano', 'drums', 'harp', 'table']


def f(x):
    s = repr(round(float(x), 6))
    if s == '-0.0':
        s = '0.0'
    return s + 'f'


def v3(p):  # right-handed position -> Unity
    return f'new Vector3({f(p[0])}, {f(p[1])}, {f(-p[2])})'


def yaw_deg(y3):  # right-handed yaw (rad) -> Unity yaw (deg) in (-180, 180]
    a = -float(y3) * 180.0 / math.pi
    while a <= -180.0:
        a += 360.0
    while a > 180.0:
        a -= 360.0
    return a


def opt_float(x):
    return 'float.NaN' if x is None else f(x)


lines = []
w = lines.append
w('// GENERATED by Reference~/gen_fixture.py from Reference~/layout-golden.json, the frozen layout golden (rig parts,')
w('// footprints, seats and placement outcomes), converted to Unity coordinates (z negated, yaw negated, rig-local z')
w('// negated). The "fixed" fitSeat outcomes are the resolver run with the dry-run clearEye fix. Do not edit by hand.')
w('using UnityEngine;')
w('')
w(f'namespace {ns}')
w('{')
w('    internal static class GoldenLayout')
w('    {')
w('        public const int Piano = 0, Drums = 1, Harp = 2, Table = 3;')
w('        public const int FlagHandle = 1, FlagPlayed = 2, FlagStick = 4;')
w('        public static readonly string[] RigNames = { "piano", "drums", "harp", "table" };')
w('')
w('        /// <summary>One measured part: its oriented box in the rig frame (Unity), flags, mesh name.</summary>')
w('        public struct Part { public int Rig, Flags; public Vector3 C, A0, A1, A2, H; public string Name; }')
w('        public struct Rect4 { public float X, Z, Hx, Hz; public Rect4(float x, float z, float hx, float hz) { X = x; Z = z; Hx = hx; Hz = hz; } }')
w('        public struct RigPose { public bool InScene; public Vector3 Pos; public float YawDeg; }')
w('        public struct DrumPiece { public string Kind; public bool Pad, Cymbal; public float R; public Vector3 Pos; public Quaternion Rot; }')
w('')
w('        public static readonly Part[] Parts =')
w('        {')
for ri, n in enumerate(RIGS):
    for p in d['rigs'][n]['parts']:
        if not p['shows']:
            continue
        flags = (1 if p['handle'] else 0) | (0 if p['handle'] else 2) | (4 if p['stick'] else 0)
        ax = p['ax']
        a0 = (ax[0][0], ax[0][1], -ax[0][2])
        a1 = (ax[1][0], ax[1][1], -ax[1][2])
        a2 = (ax[2][0], ax[2][1], -ax[2][2])
        c = p['c']
        h = p['h']
        w(f'            new Part {{ Rig = {ri}, Flags = {flags}, C = new Vector3({f(c[0])}, {f(c[1])}, {f(-c[2])}), '
          f'A0 = new Vector3({f(a0[0])}, {f(a0[1])}, {f(a0[2])}), A1 = new Vector3({f(a1[0])}, {f(a1[1])}, {f(a1[2])}), '
          f'A2 = new Vector3({f(a2[0])}, {f(a2[1])}, {f(a2[2])}), H = new Vector3({f(h[0])}, {f(h[1])}, {f(h[2])}), Name = "{p["name"]}" }},')
w('        };')
w('')
w('        /// <summary>The play centre of each rig (the rig\'s centre()), rig-local Unity.</summary>')
w('        public static readonly Vector3[] CentreLocal = { ' + ', '.join(v3(d['rigs'][n]['centreLocal']) for n in RIGS) + ' };')
w('        /// <summary>The rig measure: the floor rectangles kept after dropping contained ones, and their bound (rig frame).</summary>')
w('        public static readonly Rect4[][] Rects =')
w('        {')
for n in RIGS:
    rs = d['rigs'][n]['rects']
    w('            new[] { ' + ', '.join(f'new Rect4({f(x["x"])}, {f(-x["z"])}, {f(x["hx"])}, {f(x["hz"])})' for x in rs) + ' },')
w('        };')
w('        public static readonly Rect4[] Bound = { ' + ', '.join(
    f'new Rect4({f(d["rigs"][n]["bound"]["x"])}, {f(-d["rigs"][n]["bound"]["z"])}, {f(d["rigs"][n]["bound"]["hx"])}, {f(d["rigs"][n]["bound"]["hz"])})' for n in RIGS) + ' };')
w('')
w('        /// <summary>The menu panel\'s two plates (face, back) as boxes in the panel frame (Unity: the visible side is -z).</summary>')
w('        public static readonly Part[] PanelBoxes =')
w('        {')
for b in d['panel']['boxes']:
    c, h = b['c'], b['h']
    w(f'            new Part {{ Rig = -1, Flags = 1, C = new Vector3({f(c[0])}, {f(c[1])}, {f(-c[2])}), A0 = Vector3.right, A1 = Vector3.up, A2 = Vector3.forward, '
      f'H = new Vector3({f(h[0])}, {f(h[1])}, {f(h[2])}), Name = "panel" }},')
w('        };')
w('')
z = d['zones']
w(f'        public const float PianoX0 = {f(z["piano"]["x0"])}, PianoL = {f(z["piano"]["L"])};')
w('        public static readonly DrumPiece[] DrumPieces =')
w('        {')
for pc in z['drums']:
    q = pc['quat']
    w(f'            new DrumPiece {{ Kind = "{pc["kind"]}", Pad = {"true" if pc["pad"] else "false"}, Cymbal = {"true" if pc["type"] == "cymbal" else "false"}, '
      f'R = {f(pc["r"])}, Pos = {v3(pc["pos"])}, Rot = new Quaternion({f(-q[0])}, {f(-q[1])}, {f(q[2])}, {f(q[3])}) }},')
w('        };')
w('        public static readonly Vector3 HatPos = ' + v3(z['hat']['pos']) + ';')
w('        public static readonly Vector3[] HarpA = { ' + ', '.join(v3(s['a']) for s in z['harp']) + ' };')
w('        public static readonly Vector3[] HarpB = { ' + ', '.join(v3(s['b']) for s in z['harp']) + ' };')
w('        public static readonly Vector3 DeckPos = ' + v3(z['deckPos']) + ';')
w('        public static readonly Vector2[] DeckButtons = { ' + ', '.join(f'new Vector2({f(b["x"])}, {f(-b["z"])})' for b in z['deckButtons']) + ' };')
w('        public static readonly Vector3 SwitchPanelPos = ' + v3(z['panelPos']) + ';')
w(f'        public const float SwitchPanelYawDeg = {f(yaw_deg(z["panelYaw"]))};')
w('        public static readonly float[] ToggleX = { ' + ', '.join(f(t['x']) for t in z['toggles']) + ' };')
w('')

# ---- scenarios ----
w('        public sealed class Scenario')
w('        {')
w('            public string Label; public bool Single; public int Inst; public Vector3 Head; public float YawDeg; public bool Ar;')
w('            public RigPose[] After; public float[] Eye; public string[] Moved; public int Overlaps2D, Overlaps3D;')
w('            public bool HasGoldenShift, HasFixedShift; public Vector2 GoldenShift, FixedShift;')
w('            public Vector3 FixedHead; public RigPose[] FixedAfter; public float[] FixedEye; public string[] FixedMoved; public int FixedOverlaps2D;')
w('        }')
w('')


def poses(snap):
    out = []
    for n in RIGS:
        a = snap[n]
        out.append(f'new RigPose {{ InScene = {"true" if a["inScene"] and a["visible"] else "false"}, Pos = {v3(a["pos"])}, YawDeg = {f(yaw_deg(a["yaw"]))} }}')
    return 'new[] { ' + ', '.join(out) + ' }'


def eyes(e):
    return 'new[] { ' + ', '.join(opt_float(e.get(n) if e else None) for n in RIGS) + ' }'


def moved(rep):
    if not rep:
        return 'new string[0]'
    return 'new[] { ' + ', '.join(f'"{m["name"]}"' for m in rep['moves']) + ' }' if rep['moves'] else 'new string[0]'


inst_index = {None: -1, 'piano': 0, 'drums': 1, 'harp': 2}
w('        public static readonly Scenario[] Scenarios =')
w('        {')
for s in d['scenarios']:
    seat = s['seat']
    head = f'new Vector3({f(seat[0])}, {f(seat[1])}, {f(-seat[2])})'
    yawu = yaw_deg(s['yawDeg'] * math.pi / 180.0)
    parts = [f'Label = "{s["label"]}"', f'Single = {"true" if s["mode"] == "single" else "false"}', f'Inst = {inst_index[s["inst"]]}',
             f'Head = {head}', f'YawDeg = {f(yawu)}', f'Ar = {"true" if s["ar"] else "false"}',
             f'After = {poses(s["after"])}', f'Eye = {eyes(s["eye"])}', f'Moved = {moved(s["report"])}',
             f'Overlaps2D = {s["overlaps2D"]}', f'Overlaps3D = {s["overlaps3D"]}']
    if not s['ar']:
        ws, fs = s.get('goldenShift'), s.get('fixedShift')
        parts.append(f'HasGoldenShift = {"true" if ws else "false"}')
        if ws:
            parts.append(f'GoldenShift = new Vector2({f(ws[0])}, {f(-ws[1])})')
        parts.append(f'HasFixedShift = {"true" if fs else "false"}')
        if fs:
            parts.append(f'FixedShift = new Vector2({f(fs[0])}, {f(-fs[1])})')
        parts.append(f'FixedHead = {v3(s["fixedHead"])}')
        parts.append(f'FixedAfter = {poses(s["fixedAfter"])}')
        parts.append(f'FixedEye = {eyes(s["fixedEye"])}')
        parts.append(f'FixedMoved = {moved(s["fixedReport"])}')
        parts.append(f'FixedOverlaps2D = {s["fixedOverlaps2D"]}')
    w('            new Scenario { ' + ', '.join(parts) + ' },')
w('        };')
w('')

# ---- constrain / settle / clearPanel cases ----
c = d['cases']
pk = c['pushKitIntoPiano']
w('        // placement.constrain: the kit pushed toward the piano in 25 steps of 2 cm (start = all-mode home at the origin seat)')
w(f'        public static readonly Vector3 PushStart = {v3(pk["start"])};')
w(f'        public const float PushYawDeg = {f(yaw_deg(pk["yaw"]))};')
w(f'        public static readonly Vector3 PushDir = {v3(pk["dir"])};')
w('        public static readonly Vector3[] PushPath = { ' + ', '.join(v3(p['pos']) for p in pk['path']) + ' };')
w('        public static readonly bool[] PushLimited = { ' + ', '.join('true' if p['lim'] else 'false' for p in pk['path']) + ' };')
bm = c['bigMoveKit']
w(f'        public static readonly Vector3 BigMoveTarget = {v3(bm["target"])}, BigMoveEnd = {v3(bm["end"])};')
ta = c['turnAtContact']
w(f'        public static readonly Vector3 TurnAt = {v3(ta["at"])};')
w('        public static readonly float[] TurnTriesDeg = { ' + ', '.join(f(-t['dy'] * 180 / math.pi) for t in ta['turns']) + ' };')
w('        public static readonly bool[] TurnRefused = { ' + ', '.join('true' if (t['lim'] and abs(t['yaw'] - ta['yaw']) < 1e-6) else 'false' for t in ta['turns']) + ' };')
om = c['overlapMovesFreely']
w(f'        public static readonly Vector3 OverlapStart = {v3(om["start"])}, OverlapEnd = {v3(om["end"])};')
sk = c['settleKitInPiano']
w(f'        public static readonly Vector3 SettleKitStart = {v3(sk["start"])}, SettleKitEnd = {v3(sk["end"])};')
w(f'        public const float SettleKitBy = {f(sk["by"])}, SettleKitEye = {f(sk["eye"])};')
sh = c['settleHarpInFace']
w(f'        public static readonly Vector3 SettleHarpStart = {v3(sh["start"])}, SettleHarpEnd = {v3(sh["end"])};')
w(f'        public const float SettleHarpYawDeg = {f(yaw_deg(sh["yaw"]))}, SettleHarpEye0 = {f(sh["eye0"])}, SettleHarpEye = {f(sh["eye"])}, SettleHarpBy = {f(sh["by"])};')
st = c['settleTableInWall']
w(f'        public static readonly Vector3 SettleTableStart = {v3(st["start"])}, SettleTableEnd = {v3(st["end"])};')
w(f'        public const float SettleTableYawDeg = {f(yaw_deg(st["yaw"]))}, SettleTableBy = {f(st["by"])};')
for key, name in [('clearPanelFromPiano', 'PanelFromPiano'), ('clearPanelFromKit', 'PanelFromKit'), ('clearPanelFree', 'PanelFree')]:
    cp = c[key]
    y0 = cp.get('yaw0', 0)
    w(f'        public static readonly Vector3 {name}Start = {v3(cp["start"])}, {name}End = {v3(cp["end"])};')
    w(f'        public const float {name}Yaw0Deg = {f(yaw_deg(y0))}, {name}YawDeg = {f(yaw_deg(cp["yaw"]))};')
    w(f'        public const bool {name}Hit = {"true" if cp["hits0"] else "false"}, {name}Ok = {"true" if cp["ok"] else "false"};')
w('')

# ---- grab targets ----
w('        public struct GrabPoint { public string Label; public Vector3 P; public string Target, Surface; public bool Near; }')
w('        public static readonly GrabPoint[] GrabPoints =')
w('        {')
for k, g in d['grab'].items():
    t = f'"{g["target"]}"' if g['target'] else 'null'
    sfc = f'"{g["surface"]}"' if g['surface'] else 'null'
    w(f'            new GrabPoint {{ Label = "{k}", P = {v3(g["p"])}, Target = {t}, Surface = {sfc}, Near = {"true" if g["near"] else "false"} }},')
w('        };')
zw = d['zonesWorld']
w('        /// <summary>The grab zones (each rig\'s world bounding box + 0.12 m) at the origin seat, all mode: min / max (Unity).</summary>')
for n in ['piano', 'drums', 'harp', 'table', 'lessons']:
    zz = zw[n]
    mn = (zz['min'][0], zz['min'][1], -zz['max'][2])
    mx = (zz['max'][0], zz['max'][1], -zz['min'][2])
    w(f'        public static readonly Bounds Zone{n.capitalize()} = new Bounds(new Vector3({f((mn[0] + mx[0]) / 2)}, {f((mn[1] + mx[1]) / 2)}, {f((mn[2] + mx[2]) / 2)}), '
      f'new Vector3({f(mx[0] - mn[0])}, {f(mx[1] - mn[1])}, {f(mx[2] - mn[2])}));')
w('')
tr = d['turn']
w('        // startTurn after a swivel: single drums at seat (0, 1.2, -0.1) yaw 0, then the seat at (0.3, 1.2, -0.1) facing +x and next(+1)')
w(f'        public static readonly Vector3 TurnKitRest = {v3(tr["kit0"]["drums"]["pos"])}, TurnTableRest = {v3(tr["kit0"]["table"]["pos"])};')
w(f'        public static readonly Vector3 TurnRestIn = {v3(tr["mid"]["restIn"])}, TurnRestOut = {v3(tr["mid"]["restOut"])}, TurnRight = {v3(tr["mid"]["right"])};')
w(f'        public static readonly Vector3 TurnHarpAfter = {v3(tr["afterHarp"]["harp"]["pos"])}, TurnTableAfter = {v3(tr["afterHarp"]["table"]["pos"])};')
w(f'        public const float TurnHarpAfterYawDeg = {f(yaw_deg(tr["afterHarp"]["harp"]["yaw"]))};')
w('    }')
w('}')
open(out_path, 'w').write('\n'.join(lines) + '\n')
print('wrote', out_path, len(lines), 'lines')
